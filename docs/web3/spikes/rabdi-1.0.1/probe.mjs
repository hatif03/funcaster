import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createPublicClient as arkivClient} from '@arkiv-network/sdk';
import {rabdi} from '@arkiv-network/sdk/chains';
import {createPublicClient,http} from 'viem';
import {addEnsContracts} from '@ensdomains/ensjs';
import {sepolia} from 'viem/chains';
const owner='0xE581E56c592Ab9D6d3D234168EE9a89032273c00';
const report={at:new Date().toISOString(),scope:'Historical initial scratch probe: public anonymous reads; migration subsequently approved Nov 6',sdk:'1.0.1',viem:'2.57.14',ensjs:'5.2.7',checks:[]};
const c=arkivClient({chain:rabdi({accessKey:''}),transport:http(undefined,{timeout:12000,retryCount:0,fetchOptions:{redirect:'error'}}),cacheTime:0});
const chainId=await c.getChainId();assert.equal(chainId,7794095);
report.chainId=chainId;
report.balanceWei=String(await c.getBalance({address:owner}));
const page=await c.select({$key:true,$creator:true}).createdBy(owner).limit(1).fetch();
report.checks.push({id:'creator-scoped anonymous read',status:'PASS-READ',count:page.entities.length,block:String(page.blockNumber)});
const ens=createPublicClient({chain:addEnsContracts(sepolia),transport:http('https://ethereum-sepolia-rpc.publicnode.com',{timeout:15000,retryCount:0})});
report.checks.push({id:'ENS same-process read',status:'PASS-READ',chainId:await ens.getChainId(),address:await ens.getEnsAddress({name:'funcaster.eth'})});
await fs.writeFile('evidence.json',JSON.stringify(report,null,2)+'\n');
